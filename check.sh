#!/usr/bin/env bash
# Проверка по заданиям. Каждое задание, у которого есть что проверить по тексту
# страницы, идёт своей секцией: «Задание 1», «Задание 2», «Задание 4». Так
# сразу видно, какое старое задание сломалось. В секцию попадают только
# предикаты, которые скрипт может проверить надёжно; остальные (источник
# данных, содержимое PDF, игра, анимация) проверяются глазами.
#
#     ./check.sh
#
# Только bash и то, что есть в системе (grep, sed, awk). Страницу в браузере
# скрипт не открывает: он читает текст index.html. Поэтому он проверяет то, что
# можно найти в тексте, а то, что видно только глазами, честно помечено ниже.

set -uo pipefail

PAGE=index.html
FAIL=0

g() { printf '\033[32m%s\033[0m' "$1"; }
r() { printf '\033[31m%s\033[0m' "$1"; }

# Причины красного копятся здесь и печатаются под строкой предиката.
REASONS=()
why() { REASONS+=("$1"); }

# Печатает одну строку предиката: ДА, если причин нет, иначе НЕТ и причины.
verdict() {
  if [ "${#REASONS[@]}" -eq 0 ]; then
    printf '  [ %s ] %s\n' "$(g 'ДА ')" "$1"
  else
    printf '  [ %s ] %s\n' "$(r 'НЕТ')" "$1"
    for x in "${REASONS[@]}"; do printf '        -> %s\n' "$x"; done
    FAIL=$((FAIL+1))
  fi
  REASONS=()
}

# Цвет #rgb или #rrggbb -> три числа "R G B" (0..255).
rgb() {
  local h="${1#\#}"
  [ "${#h}" -eq 3 ] && h="${h:0:1}${h:0:1}${h:1:1}${h:1:1}${h:2:1}${h:2:1}"
  printf '%d %d %d' "0x${h:0:2}" "0x${h:2:2}" "0x${h:4:2}"
}

# Заголовок секции задания.
section() { printf '\n  %s\n' "$1"; }

echo
echo "  Проверка по заданиям"
echo "  ----------------------------------------------"

if [ ! -s "$PAGE" ]; then
  printf '  [ %s ] страница %s не найдена или пустая\n' "$(r 'НЕТ')" "$PAGE"
  printf '\n  %s\n\n' "$(r 'КРАСНОЕ')"
  exit 1
fi

# Всё, что внутри <style>...</style>.
CSS=$(sed -n '/<style>/,/<\/style>/p' "$PAGE")

# Карточки компаний: каждая лежит в <li ...> на одной строке.
CARDS=$(grep '<li' "$PAGE")
N_CARDS=$(printf '%s\n' "$CARDS" | grep -c '<li')
# Название компании из строки карточки (для понятных причин красного).
card_name() { printf '%s' "$1" | sed -n 's/.*class="name"[^>]*>\([^<]*\)<.*/\1/p'; }

# ===========================================================================
section "Задание 1 (zadanie-1.md)"
# ===========================================================================

# 1.1. Список состоит минимум из 15 строк.
# ГЛАЗАМИ: что каждая строка именно название компании, а не мусор.
[ "$N_CARDS" -ge 15 ] || why "в списке $N_CARDS строк (<li>), нужно минимум 15"
verdict "1.1 В списке минимум 15 строк"

# 1.3. Список отсортирован от самых богатых к менее богатым.
# Берутся суммы, которые видит читатель («≈ 5,0 трлн $»), а не служебные
# переменные. Каждая следующая не должна быть больше предыдущей.
# ГЛАЗАМИ (предикат 1.2): что суммы правда за 2026 год и взяты из надёжных
# данных. Скрипт видит порядок чисел, но не знает, настоящие ли они.
SUMS=$(grep -oE 'class="cap">[^<]*' "$PAGE" | grep -oE '[0-9]+([,.][0-9]+)?' | tr ',' '.')
N_SUMS=$(printf '%s\n' "$SUMS" | grep -c .)
if [ "$N_SUMS" -ne "$N_CARDS" ]; then
  why "сумм на странице $N_SUMS, карточек $N_CARDS: не у каждой карточки есть сумма"
else
  BAD=$(printf '%s\n' "$SUMS" | awk 'NR>1 && $1+0 > prev+0 {printf "%s после %s; ", $1, prev} {prev=$1}')
  [ -z "$BAD" ] || why "порядок нарушен: $BAD"
fi
verdict "1.3 Отсортировано от самых богатых к менее богатым"

# ===========================================================================
section "Задание 2 (zadanie-2.md)"
# ===========================================================================

# 2.1. Рядом с каждым названием есть логотип из Google (favicons).
# ГЛАЗАМИ: что логотип загружается и это логотип именно этой компании:
# скрипт видит адрес картинки, но не открывает его.
while IFS= read -r line; do
  printf '%s' "$line" | grep -qE '<img[^>]*src="https://www\.google\.com/s2/favicons\?[^"]*domain=[^"&]+' \
    || why "у «$(card_name "$line")» нет логотипа с google.com/s2/favicons"
done <<<"$CARDS"
verdict "2.1 У каждой компании есть логотип из Google"

# 2.2. При наведении на название видны год основания и CEO.
# Подсказка берётся из data-info у .name: нужен четырёхзначный год и CEO.
# ГЛАЗАМИ: что подсказка правда появляется при наведении и что данные
# верны (источник Forbes): скрипт проверяет, что текст задан, не его правдивость.
while IFS= read -r line; do
  info=$(printf '%s' "$line" | grep -oE 'class="name"[^>]*data-info="[^"]*"' | sed 's/.*data-info="//; s/"$//')
  nm=$(card_name "$line")
  if [ -z "$info" ]; then
    why "у «$nm» нет подсказки data-info"
  else
    printf '%s' "$info" | grep -qE 'Основана:[[:space:]]*[0-9]{4}' || why "у «$nm» в подсказке нет года основания"
    printf '%s' "$info" | grep -qE 'CEO:[[:space:]]*[^[:space:]]'  || why "у «$nm» в подсказке нет CEO"
  fi
done <<<"$CARDS"
verdict "2.2 У каждой компании в подсказке год основания и CEO"

# ===========================================================================
section "Задание 4 (zadanie-4.md)"
# ===========================================================================

# ---------------------------------------------------------------------------
# Предикат 1. Тёмный фон (графит или глубокий синий) + неоново-зелёные и
# красные акценты.
#
# Проверяется по тексту CSS:
#   - основной фон: первый цвет у --bg (или у background в body), он должен
#     быть тёмным: яркость меньше 64 из 255;
#   - в CSS есть неоново-зелёный цвет (G >= 200, R <= 120, B <= 140);
#   - в CSS есть красный цвет (R >= 200, G <= 100, B <= 100).
# Пороги выбрал я, чтобы слово «неоновый» стало числом. Измени, если не так.
#
# ГЛАЗАМИ: «в стиле биржевых терминалов» и то, что акценты действительно
# выглядят неоновыми. Это вкус, скрипт его не видит.
# ---------------------------------------------------------------------------
BG=$(printf '%s\n' "$CSS" | grep -oiE -- '--bg:[[:space:]]*#[0-9a-f]{3,6}' | head -1 | grep -oiE '#[0-9a-f]{3,6}')
if [ -z "$BG" ]; then
  BG=$(printf '%s\n' "$CSS" | tr '\n' ' ' | grep -oiE 'body[^}]*background(-color)?:[[:space:]]*#[0-9a-f]{3,6}' | head -1 | grep -oiE '#[0-9a-f]{3,6}$')
fi
if [ -z "$BG" ]; then
  why "не нашёл цвет основного фона (--bg или background у body)"
else
  read -r R G B <<<"$(rgb "$BG")"
  LUM=$(( (299*R + 587*G + 114*B) / 1000 ))
  [ "$LUM" -lt 64 ] || why "основной фон $BG светлый (яркость $LUM из 255, нужно меньше 64)"
fi
HAS_GREEN=0; HAS_RED=0
for c in $(printf '%s\n' "$CSS" | grep -oiE '#[0-9a-f]{6}\b|#[0-9a-f]{3}\b'); do
  read -r R G B <<<"$(rgb "$c")"
  [ "$G" -ge 200 ] && [ "$R" -le 120 ] && [ "$B" -le 140 ] && HAS_GREEN=1
  [ "$R" -ge 200 ] && [ "$G" -le 100 ] && [ "$B" -le 100 ] && HAS_RED=1
done
[ "$HAS_GREEN" -eq 1 ] || why "в CSS нет неоново-зелёного цвета"
[ "$HAS_RED" -eq 1 ]   || why "в CSS нет красного цвета"
verdict "4.1 Фон тёмный, акценты неоново-зелёные и красные"

# ---------------------------------------------------------------------------
# Предикат 2. Таблица заменена на плиточную сетку (Bento Grid), размер
# карточки зависит от капитализации.
#
# Проверяется по тексту:
#   - в странице нет <table>;
#   - в CSS есть display: grid;
#   - в странице 20 карточек компаний и у каждой есть свой размер:
#     grid-column / grid-row со span, или переменная --размер / --size / --cap,
#     или width / flex-basis прямо в style карточки.
#
# ГЛАЗАМИ: что размер именно ПРОПОРЦИОНАЛЕН капитализации (Nvidia заметно
# больше Mastercard, а не чуть-чуть). Скрипт видит, что размер задан, но не
# видит, как карточки выглядят в браузере. Открой страницу и сравни.
# ---------------------------------------------------------------------------
grep -qi '<table' "$PAGE" && why "в странице всё ещё есть <table>"
printf '%s\n' "$CSS" | tr '\n' ' ' | grep -qiE 'display:[[:space:]]*grid' \
  || why "в CSS нет display: grid, плиточной сетки не нашёл"
SIZED=$(grep -ciE 'style="[^"]*(grid-column|grid-row|--size|--размер|--cap|--cap-|width|flex-basis)' "$PAGE")
SPANS=$(printf '%s\n' "$CSS" | grep -ciE 'grid-(column|row):[[:space:]]*span')
if [ "$SIZED" -lt 20 ] && [ "$SPANS" -lt 3 ]; then
  why "не нашёл размеров карточек: в style у карточек их $SIZED из 20, правил span в CSS $SPANS"
fi
verdict "4.2 Таблица заменена на плиточную сетку, размер карточки задан по капитализации"

# ---------------------------------------------------------------------------
# Предикат 3. Карточка подсвечивается фирменным цветом компании при наведении.
#
# Раньше здесь искали слово: «рядом с названием есть #rrggbb». Так можно
# написать цвет руками, и подсветка при этом не работала бы. Теперь проверяется
# цепочка, по которой цвет доходит до экрана:
#   1. есть правило :hover на самой карточке (тот же тег или класс, что у
#      карточки компании), а не на .name (там старая подсказка);
#   2. подсветка в этом правиле (background, border-color, box-shadow, outline)
#      берёт цвет из переменной: var(--что-то), а не пишет один цвет для всех;
#   3. эту переменную задаёт КАЖДАЯ из 20 карточек, своим значением #rrggbb
#      (в style самой карточки);
#   4. все 20 значений разные: один и тот же цвет у всех не «бренды».
# Если разорвать любое звено (убрать var(), убрать значение у одной карточки,
# повесить :hover не на карточку, покрасить всех одинаково), строка станет НЕТ,
# даже если подходящий текст на странице остался.
#
# Что скрипт по-прежнему НЕ видит, и это проверяется ГЛАЗАМИ:
#   - что :hover реально срабатывает в браузере: каскад или другое правило
#     могут перебить его, скрипт этого не вычисляет;
#   - что цвет у карточки правда фирменный (#e31937 у Tesla или случайный
#     красный): скрипт знает только, что цвета заданы и разные;
#   - что подсветка заметна на тёмном фоне (тёмно-синий бренд почти не светит);
#   - реализация без переменной (по отдельному :hover-правилу на каждую
#     компанию) даст НЕТ: скрипт требует именно механизм с var(--…).
# ---------------------------------------------------------------------------
# Строка карточки компании: в ней есть название и атрибут style.
card_line() { grep -iE "$1" "$PAGE" | grep -E 'style="' | head -1; }

HOVER=$(printf '%s\n' "$CSS" | tr '\n' ' ' | grep -oiE '[^{}]*:hover[^{}]*\{[^}]*\}' | grep -viE '^[[:space:]]*\.name' || true)
BRANDVAR=""
if [ -z "$HOVER" ]; then
  why "нет правила :hover для карточки (есть только для .name, или совсем нет)"
else
  # 1. правило :hover стоит на том же элементе, что и карточка
  TAG=$(card_line Nvidia | grep -oE '<[a-zA-Z0-9]+' | head -1 | tr -d '<')
  CLS=$(card_line Nvidia | grep -oE '^[^>]*>' | grep -oE 'class="[^"]*"' | head -1 | sed 's/class="\([^" ]*\).*/\1/')
  SEL=$(printf '%s\n' "$HOVER" | sed 's/{.*//')
  if [ -z "$TAG" ]; then
    why "не нашёл карточку компании (строку с названием и style), не к чему привязать :hover"
  elif ! { printf '%s\n' "$SEL" | grep -qE "(^|[^a-zA-Z0-9_-])${TAG}:hover" || { [ -n "$CLS" ] && printf '%s\n' "$SEL" | grep -qE "\.${CLS}:hover"; }; }; then
    why ":hover есть ($(printf '%s' "$SEL" | head -c 40)), но не на карточке <$TAG>"
  fi
  # 2. подсветка берёт цвет из переменной, 3. её задаёт карточка
  VARS=$(printf '%s\n' "$HOVER" | grep -oiE '(background|border-color|box-shadow|outline(-color)?|border)[^;}]*' | grep -oE 'var\(--[^) ,]+' | sed 's/var(//' | sort -u)
  if [ -z "$VARS" ]; then
    why "в :hover нет подсветки с цветом из переменной var(--…): background, border-color или box-shadow"
  else
    for v in $VARS; do
      if card_line Nvidia | grep -qiE -- "${v}:[[:space:]]*#[0-9a-f]{6}\b"; then BRANDVAR="$v"; break; fi
    done
    [ -n "$BRANDVAR" ] || why "подсветка берёт цвет из ($(echo $VARS)), но карточка компании эту переменную не задаёт"
  fi
fi
if [ -n "$BRANDVAR" ]; then
  FOUND=""; MISSING=""
  for name in Nvidia Apple Microsoft Alphabet Amazon Meta Broadcom Aramco TSMC Tesla Berkshire Lilly Walmart JPMorgan Samsung Tencent Visa Oracle Exxon Mastercard; do
    c=$(card_line "$name" | grep -oiE -- "${BRANDVAR}:[[:space:]]*#[0-9a-f]{6}\b" | head -1 | grep -oiE '#[0-9a-f]{6}' | tr 'A-F' 'a-f')
    if [ -z "$c" ]; then MISSING="$MISSING $name"; else FOUND="$FOUND $c"; fi
  done
  [ -z "$MISSING" ] || why "у карточки нет значения ${BRANDVAR}: #rrggbb:$MISSING"
  DUP=$(printf '%s\n' $FOUND | sort | uniq -d | tr '\n' ' ')
  [ -z "$DUP" ] || why "цвета бренда повторяются у разных компаний: $DUP"
fi
verdict "4.3 При наведении карточка подсвечивается цветом бренда"

echo "  ----------------------------------------------"
if [ "$FAIL" -eq 0 ]; then
  printf '  %s\n\n' "$(g 'ЗЕЛЁНОЕ')"
else
  printf '  %s\n\n' "$(r 'КРАСНОЕ')"
fi

[ "$FAIL" -eq 0 ]
