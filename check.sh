# 1.1. Список состоит минимум из 15 строк.
# ГЛАЗАМИ: что каждая строка именно название компании, а не мусор.
[ "$N_CARDS" -ge 15 ] || why "в списке $N_CARDS строк (<li>), нужно минимум 15"
verdict "1.1 В списке минимум 15 строк"

# 1.3. Список отсортирован от самых богатых к менее богатым.
# Берутся суммы, которые видит читатель («≈ 5,0 трлн $»), а не служебные
# переменные. Каждая следующая не должна быть больше предыдущей.
# ГЛАЗАМИ (предикат 1.2): что суммы правда за 2026 год и взяты из надёжных
# данных. Скрипт видит порядок чисел, но не знает, настоящие ли они.
SUMS=$(grep -oE 'class="cap">[^<]*' "$PAGE" | grep -oE '[0-9]+([,.][0-9]+)?' | tr ',' '.')
N_SUMS=$(printf '%s\n' "$SUMS" | grep -c .)
if [ "$N_SUMS" -ne "$N_CARDS" ]; then
  why "сумм на странице $N_SUMS, карточек $N_CARDS: не у каждой карточки есть сумма"
else
  BAD=$(printf '%s\n' "$SUMS" | awk 'NR>1 && $1+0 > prev+0 {printf "%s после %s; ", $1, prev} {prev=$1}')
  [ -z "$BAD" ] || why "порядок нарушен: $BAD"
fi
verdict "1.3 Отсортировано от самых богатых к менее богатым"

