# Скрипт страницу не запускает, поэтому в поле он ничего не «вводит». Он
# проверяет цепочку, без которой поиск работать не может: поле -> функция ->
# скрытие карточек, и считает по названиям, сколько карточек должно остаться.
#
# ГЛАЗАМИ (все три предиката): открыть страницу, ввести «App», «GOOGLE»,
# «xyz», стереть текст и увидеть результат в браузере.

# Названия компаний, как их видит читатель, маленькими буквами.
NAMES=$(grep -oE 'class="name"[^>]*>[^<]*' "$PAGE" | sed 's/.*>//' | tr 'A-Z' 'a-z')
# Сколько названий содержат текст (текст тоже маленькими буквами).
count_names() { printf '%s\n' "$NAMES" | grep -cF -- "$1"; }

# Поле поиска и функция, которую оно вызывает при вводе.
INPUT=$(grep -oE '<input[^>]*placeholder="Поиск"[^>]*>' "$PAGE" | head -1)
SEARCHFN=$(printf '%s' "$INPUT" | grep -oE 'oninput="[^"(]+' | sed 's/oninput="//')
FBODY=""
[ -z "$SEARCHFN" ] || FBODY=$(sed -n "/function ${SEARCHFN}()/,/^  }/p" "$PAGE")

# 6.1. Над сеткой есть поле с подсказкой «Поиск», пока оно пустое, видны все
# 20 карточек.
#   - поле <input placeholder="Поиск"> есть и стоит в тексте выше <ol>;
#   - карточек 20, и ни одна не скрыта заранее атрибутом hidden.
if [ -z "$INPUT" ]; then
  why "нет поля <input> с подсказкой placeholder=\"Поиск\""
else
  L_IN=$(grep -nE '<input[^>]*placeholder="Поиск"' "$PAGE" | head -1 | cut -d: -f1)
  L_OL=$(grep -nE '<ol[ >]' "$PAGE" | head -1 | cut -d: -f1)
  [ -n "$L_OL" ] && [ "$L_IN" -lt "$L_OL" ] || why "поле поиска стоит не над сеткой (<ol>)"
fi
[ "$N_CARDS" -eq 20 ] || why "карточек $N_CARDS, нужно 20"
HID=$(printf '%s\n' "$CARDS" | grep -cE '<li[^>]*[[:space:]]hidden')
[ "$HID" -eq 0 ] || why "$HID карточек скрыты заранее (hidden) ещё до ввода"
verdict "6.1 Над сеткой поле «Поиск», карточек 20 и ни одна не скрыта заранее"

# 6.2. «App» -> только Apple, «GOOGLE» -> только «Alphabet (Google)», регистр
# не важен.
#   - поле при вводе вызывает функцию (oninput="имя()"), и она есть в скрипте;
#   - функция читает текст поля (.value), уравнивает регистр (toLowerCase или
#     toUpperCase) и скрывает карточки (.hidden = ...);
#   - по названиям на странице: «app» есть ровно в одном (Apple), «google»
#     ровно в одном (Alphabet (Google)). Появится вторая компания с «app» в
#     названии: строка станет НЕТ.
if [ -z "$SEARCHFN" ]; then
  why "поле поиска не вызывает функцию при вводе (нет oninput=\"имя()\")"
elif [ -z "$FBODY" ]; then
  why "в скрипте нет функции ${SEARCHFN}(), которую вызывает поле"
else
  printf '%s\n' "$FBODY" | grep -qE '\.value'                          || why "функция ${SEARCHFN}() не читает текст поля (.value)"
  printf '%s\n' "$FBODY" | grep -qE 'toLowerCase\(\)|toUpperCase\(\)'  || why "функция ${SEARCHFN}() не уравнивает регистр (нет toLowerCase): «GOOGLE» не найдётся"
  printf '%s\n' "$FBODY" | grep -qE '\.hidden[[:space:]]*='            || why "функция ${SEARCHFN}() не скрывает карточки (нет .hidden = ...)"
fi
[ "$(count_names app)" -eq 1 ] && [ "$(count_names apple)" -eq 1 ] \
  || why "«app» есть в $(count_names app) названиях, нужно ровно в одном (Apple)"
[ "$(count_names google)" -eq 1 ] && [ "$(count_names 'alphabet (google)')" -eq 1 ] \
  || why "«google» есть в $(count_names google) названиях, нужно ровно в одном (Alphabet (Google))"
verdict "6.2 «App» находит только Apple, «GOOGLE» только Alphabet (Google), регистр не важен"

# 6.3. На «xyz» появляется «Ничего не найдено», после стирания снова все 20.
#   - надпись «Ничего не найдено» есть на странице и изначально скрыта (hidden);
#   - у надписи есть id, и функция поиска показывает и прячет её по этому id;
#   - «xyz» нет ни в одном названии: иначе пример из задания нашёл бы карточку.
MSG=$(grep -E '<[a-z0-9]+[^>]*>[[:space:]]*Ничего не найдено' "$PAGE" | head -1)
if [ -z "$MSG" ]; then
  why "на странице нет надписи «Ничего не найдено»"
else
  printf '%s' "$MSG" | grep -qE '<[^>]*[[:space:]]hidden[^>]*>[[:space:]]*Ничего' \
    || why "надпись «Ничего не найдено» не скрыта изначально (нет hidden): она видна всегда"
  MSGID=$(printf '%s' "$MSG" | grep -oE 'id="[^"]+"' | head -1 | sed 's/id="//; s/"$//')
  if [ -z "$MSGID" ]; then
    why "у надписи «Ничего не найдено» нет id: функции нечем её найти"
  elif [ -n "$FBODY" ]; then
    printf '%s\n' "$FBODY" | grep -qE "getElementById\(\"${MSGID}\"\)\.hidden[[:space:]]*=" \
      || why "функция ${SEARCHFN}() не показывает и не прячет надпись (#${MSGID})"
  else
    why "нет функции поиска, которая показывала бы надпись"
  fi
fi
[ "$(count_names xyz)" -eq 0 ] || why "«xyz» нашлось в названии компании: пример из задания не сработает"
verdict "6.3 Надпись «Ничего не найдено» скрыта изначально и управляется поиском"

echo "  ----------------------------------------------"
if [ "$FAIL" -eq 0 ]; then
  printf '  %s\n\n' "$(g 'ЗЕЛЁНОЕ')"
else
  printf '  %s\n\n' "$(r 'КРАСНОЕ')"
fi

[ "$FAIL" -eq 0 ]
